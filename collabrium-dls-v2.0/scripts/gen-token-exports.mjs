// Writes the Tokens foundation page's data. The page shows and downloads the
// tokens three ways, each copied from the DLS (collabrium-dls/preview.html's
// source panel): CSS variables (src/tokens/tokens.css, the package's copy),
// the Tailwind v4 @theme mapping (src-tailwind -> playground/public/tokens/
// tailwind.css) and the JSON export (src-json -> playground/public/tokens/
// tokens.json). Re-copy the last two whenever the DLS changes them.
//   1. copies src/tokens/tokens.css to playground/public/tokens/tokens.css
//      (so all three download from one folder)
//   2. writes playground/app/_generated/token-exports.ts (the three texts),
//      as the static export can't fetch files when opened from disk.
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pub = join(root, 'playground', 'public', 'tokens');
mkdirSync(pub, { recursive: true });
copyFileSync(join(root, 'src', 'tokens', 'tokens.css'), join(pub, 'tokens.css'));

const read = f => readFileSync(join(pub, f), 'utf8').replace(/\n$/, '');
const css = read('tokens.css');
const tailwind = read('tailwind.css');
const json = read('tokens.json');
const count = new Set(css.match(/--[a-z0-9-]+(?=\s*:)/g)).size;
const version = JSON.parse(json).version;

const out = `// Generated by scripts/gen-token-exports.mjs. Do not edit.
export const tokenCount = ${count};
export const jsonVersion = ${JSON.stringify(version)};
export const tokenExports = {
  css: ${JSON.stringify(css)},
  tailwind: ${JSON.stringify(tailwind)},
  json: ${JSON.stringify(json)},
};
`;
const dir = join(root, 'playground', 'app', '_generated');
mkdirSync(dir, { recursive: true });
writeFileSync(join(dir, 'token-exports.ts'), out);
console.log(`Token exports: ${count} tokens, JSON v${version}`);
