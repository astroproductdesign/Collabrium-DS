// Writes playground/app/_generated/changelog.ts from CHANGELOG.md, for the
// docs site's Changelog page and the version flag in its top bar. Generated
// rather than read at run time, because the static export opens from disk
// and can't fetch files.
//
// Each entry in CHANGELOG.md is a heading
//   ## v<version> · <YYYY-MM-DD> · <summary>
// then a lead paragraph, then the body paragraphs. Paragraphs are separated
// by a blank line; their hard-wrapped lines are joined back with spaces.
//
// The Download zip leaves CHANGELOG.md out (maintainer-only), so without it
// the page is empty and the flag falls back to package.json's version.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = join(root, 'CHANGELOG.md');
const pkgVersion = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')).version;

const HEADING = /^## v(\d+\.\d+\.\d+) · (\d{4}-\d{2}-\d{2}) · (.+)$/;
const entries = [];

if (existsSync(src)) {
  const blocks = readFileSync(src, 'utf8').split(/^(?=## )/m).slice(1);
  for (const block of blocks) {
    const [first, ...rest] = block.split('\n');
    const m = first.match(HEADING);
    if (!m) throw new Error(`CHANGELOG.md: a heading doesn't match "## v1.2.3 · YYYY-MM-DD · Summary": ${first}`);
    const paragraphs = rest
      .join('\n')
      .split(/\n\s*\n/)
      .map(p => p.replace(/\s*\n\s*/g, ' ').trim())
      .filter(Boolean);
    if (!paragraphs.length) throw new Error(`CHANGELOG.md: v${m[1]} has no lead paragraph`);
    entries.push({ version: m[1], date: m[2], title: m[3].trim(), lead: paragraphs[0], body: paragraphs.slice(1) });
  }
  const latest = entries[0]?.version;
  if (latest && latest !== pkgVersion) {
    // The flag shows the newest entry; package.json must say the same, or the site and the package disagree.
    throw new Error(`gen-changelog: CHANGELOG.md's newest entry is v${latest} but package.json says ${pkgVersion}. Set them to match.`);
  }
}

const out = `// Generated by scripts/gen-changelog.mjs from CHANGELOG.md. Do not edit.
export interface ChangelogEntry {
  version: string;
  date: string;
  title: string;
  /** The first paragraph. */
  lead: string;
  /** The rest, as paragraphs with inline **bold**, \`code\` and [links](url). */
  body: string[];
}

export const changelog: ChangelogEntry[] = ${JSON.stringify(entries, null, 2)};

/** The newest entry's version, or package.json's when there is no changelog. */
export const currentVersion = ${JSON.stringify(entries[0]?.version ?? pkgVersion)};
`;

const outDir = join(root, 'playground', 'app', '_generated');
mkdirSync(outDir, { recursive: true });
writeFileSync(join(outDir, 'changelog.ts'), out);
console.log(`gen-changelog: ${entries.length} entries, current version ${entries[0]?.version ?? pkgVersion}`);
