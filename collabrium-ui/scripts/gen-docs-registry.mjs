// Generates the docs site's component registry from what exists in
// src/components: every folder with a <Name>.docs.tsx becomes a page.
// Writes two files so server code never imports the docs modules (which
// contain client-only code):
//   playground/app/_generated/components-meta.ts  plain data (server-safe)
//   playground/app/_generated/components-docs.ts  docs modules (client only)
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const compDir = `${root}src/components`;
const outDir = `${root}playground/app/_generated`;

const slugify = s => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();

const entries = readdirSync(compDir, { withFileTypes: true })
  .filter(d => d.isDirectory() && existsSync(`${compDir}/${d.name}/${d.name}.docs.tsx`))
  .map(d => {
    const name = d.name;
    const docsSrc = readFileSync(`${compDir}/${name}/${name}.docs.tsx`, 'utf8');
    const m = /export const title\s*=\s*(['"])(.+?)\1/.exec(docsSrc);
    if (!m) throw new Error(`${name}.docs.tsx must export a string \`title\``);
    const compFile = `${compDir}/${name}/${name}.tsx`;
    const client = existsSync(compFile) && /^\s*['"]use client['"]/.test(readFileSync(compFile, 'utf8'));
    return { folder: name, slug: slugify(name), title: m[2], client };
  });

// Alphabetical by label (the DLS site's rule)...
entries.sort((a, b) => a.title.localeCompare(b.title, 'en', { sensitivity: 'base' }));
// ...except Charts sits directly above Chart color mapping.
const charts = entries.findIndex(e => e.title === 'Charts');
const chartMap = entries.findIndex(e => e.title === 'Chart color mapping');
if (charts > -1 && chartMap > -1 && charts !== chartMap - 1) {
  const [c] = entries.splice(charts, 1);
  entries.splice(entries.findIndex(e => e.title === 'Chart color mapping'), 0, c);
}

mkdirSync(outDir, { recursive: true });
const header = '// GENERATED by scripts/gen-docs-registry.mjs. Do not edit.\n';

writeFileSync(`${outDir}/components-meta.ts`, `${header}
export interface ComponentMeta {
  slug: string;
  title: string;
  /** True when the component file starts with "use client". */
  client: boolean;
}

export const componentsMeta: ComponentMeta[] = ${JSON.stringify(
  entries.map(({ slug, title, client }) => ({ slug, title, client })),
  null,
  2,
)};
`);

writeFileSync(`${outDir}/components-docs.ts`, `${header}
import type { ComponentDocs } from '../../../src/components/docs.types';
${entries.map(e => `import * as ${e.folder}Docs from '../../../src/components/${e.folder}/${e.folder}.docs';`).join('\n')}

export const componentDocs: Record<string, ComponentDocs> = {
${entries.map(e => `  ${JSON.stringify(e.slug)}: ${e.folder}Docs,`).join('\n')}
};
`);

console.log(`Docs registry: ${entries.map(e => e.title).join(', ') || '(none)'}`);
